export type UserFacingMessageKey = keyof typeof USER_FACING_MESSAGES
export type UserFacingMessageParamValue = string | number | boolean | null | undefined
export type UserFacingMessageParams = Record<string, UserFacingMessageParamValue>

export function formatUserFacingMessage(
  key: UserFacingMessageKey,
  params: UserFacingMessageParams = {},
): string {
  const template = USER_FACING_MESSAGES[key]
  return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => {
    const value = params[name]
    return value == null ? '' : String(value)
  })
}
