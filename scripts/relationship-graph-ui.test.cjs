const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { app, BrowserWindow } = require('electron')
const { build } = require('esbuild')
const root = path.resolve(__dirname, '..')
fs.mkdirSync(path.join(root, '.tmp-tests'), { recursive: true })
const temp = fs.mkdtempSync(path.join(root, '.tmp-tests', 'relationship-graph-ui-'))
const output = path.join(root, 'outputs', 'relationship-graph-ui')
fs.mkdirSync(output, { recursive: true })
app.setPath('userData', temp)
app.disableHardwareAcceleration()
app.commandLine.appendSwitch('force-device-scale-factor', '1')
const pause = ms => new Promise(resolve => setTimeout(resolve, ms))

async function main() {
  await app.whenReady()
  const names = ['陆闻', '阿烛', '孟安', '沈照微', '陶慎', '晏绡', '槐序', '纸姑', '何伯', '齐九', '魏铎', '池素鳞', '杜汀', '容阙', '裴执白']
  const characters = Array.from({ length: 90 }, (_, index) => ({ id: 'character:' + index, kind: 'character', name: names[index] || '图谱测试人物' + index, summary: '人物图谱的隔离验收数据。', parentId: null, attributes: { authorPlanning: { castRole: index === 0 ? 'protagonist' : 'supporting' } }, status: index < 3 ? 'confirmed' : 'planned', effectiveFromChapter: 7, source: { kind: 'ui_test' } }))
  const relations = characters.slice(1, 15).map((character, index) => ({ id: 'relationship:' + index, kind: 'relationship', fromId: index % 2 ? character.id : characters[0].id, toId: index % 2 ? characters[0].id : character.id, label: ['互相信任仍有分歧', '同行救援', '旧案的知情人与追问者', '有条件的合作'][index % 4], attributes: { bilateral: index % 3 !== 0 }, status: index < 2 ? 'confirmed' : 'planned', effectiveFromChapter: 7, source: { kind: 'ui_test' } }))
  const snapshot = { novelId: 98765, contextVersion: 1, atChapter: null, entities: characters, relations, locationChildren: [], diagnostics: [] }
  const contents = `import React from 'react';import{createRoot}from'react-dom/client';import{MemoryRouter,useNavigate}from'react-router-dom';import{ConfigProvider}from'antd';import zhCN from'antd/locale/zh_CN';import WorldAndCast from'./src/pages/Novel/AuthorWorkspace/WorldAndCast';import'./src/styles/global.css';import'./src/pages/Novel/AuthorWorkspace/author-workspace.css';const snapshot=${JSON.stringify(snapshot)};window.electron={storyAtlas:{query:async()=>snapshot},chapter:{list:async()=>[]}};function Harness(){const navigate=useNavigate();window.showPerson=id=>navigate('/novels/98765/narrative-board?tab=relationships&entity='+encodeURIComponent(id));return <main className="author-shell-main" style={{height:'100vh'}}><WorldAndCast novelId={98765}/></main>};createRoot(document.getElementById('root')).render(<ConfigProvider locale={zhCN}><MemoryRouter initialEntries={['/novels/98765/narrative-board?tab=relationships&entity=character:0']}><Harness/></MemoryRouter></ConfigProvider>);`
  await build({ stdin: { contents, loader: 'tsx', resolveDir: root }, outfile: path.join(temp, 'fixture.js'), bundle: true, alias: { '@': path.join(root, 'src') }, platform: 'browser' })
  fs.writeFileSync(path.join(temp, 'index.html'), '<meta charset="utf-8"><link rel="stylesheet" href="fixture.css"><div id="root"></div><script src="fixture.js"></script>')
  const win = new BrowserWindow({ show: false, width: 1440, height: 1000, useContentSize: true, webPreferences: { contextIsolation: false, nodeIntegration: false, backgroundThrottling: false } })
  const errors = []
  win.webContents.on('console-message', (_, level, message) => { if (level >= 3 && !message.includes('Content-Security-Policy')) errors.push(message) })
  win.webContents.session.webRequest.onBeforeRequest({ urls: ['http://*/*', 'https://*/*'] }, (_, done) => done({ cancel: true }))
  const run = async code => { try { return await win.webContents.executeJavaScript(code) } catch (error) { console.error('Renderer expression failed:', code, errors); throw error } }
  const wait = async code => { for (let i = 0; i < 200; i++) { if (await run(code)) return; await pause(25) } throw Error('Timeout: ' + code) }
  const click = label => run(`{const item=[...document.querySelectorAll('button')].find(x=>x.textContent.trim()===${JSON.stringify(label)});if(!item)throw Error('Button not found: '+${JSON.stringify(label)});item.click()}`)
  const capture = async name => { const [w, h] = win.getContentSize(); win.setContentSize(w + 1, h); await pause(80); win.setContentSize(w, h); await pause(160); fs.writeFileSync(path.join(output, name), (await win.webContents.capturePage()).toPNG()) }
  await win.loadFile(path.join(temp, 'index.html'))
  await wait('document.querySelectorAll(".react-flow__node-character").length===7')
  await pause(500)
  assert.equal(await run('document.querySelectorAll(".react-flow__edge-text").length'), 6, 'all visible edges have readable labels')
  assert.equal(await run('document.querySelectorAll(".relationship-readable-list button").length'), 14, 'full selected-person list is open even when graph contacts are paged')
  await click('下一组联系')
  await wait('document.querySelector(".relationship-contact-pages").textContent.includes("第 2 / 3 页")')
  assert.equal(await run('document.querySelectorAll(".react-flow__node-character").length'), 7)
  await click('上一组联系')
  await pause(350)
  await capture('relationships-focused-1440.png')
  await run('document.querySelector(".react-flow__controls-zoomin").click()')
  await pause(350)
  const buttonZoom = await run('document.querySelector(".react-flow__viewport").style.transform')
  await click('人物')
  await wait('!!document.querySelector(".atlas-library")')
  await click('人物关系')
  await wait('document.querySelectorAll(".react-flow__node-character").length===7')
  await pause(350)
  assert.equal(await run('document.querySelector(".react-flow__viewport").style.transform'), buttonZoom, 'programmatic zoom controls also survive unmount and return')
  await run('window.showPerson("character:89")')
  await wait('document.querySelectorAll(".react-flow__node-character").length===1 && document.querySelector(".relationship-person strong").textContent==="图谱测试人物89"')
  await click('人物')
  await wait('!!document.querySelector(".atlas-library")')
  await click('人物关系')
  await wait('document.querySelector(".relationship-person strong")?.textContent==="图谱测试人物89"')
  await click('全部人物 · 90')
  await wait('document.querySelectorAll(".react-flow__node-character").length===80')
  await wait('document.querySelectorAll(".react-flow__edge-text").length===14')
  assert.equal(await run('document.querySelectorAll(".react-flow__edge-text").length'), 14, 'overview does not hide labels when more than twelve people are visible')
  assert.equal(await run('[...document.querySelectorAll(".react-flow__node")].some(node=>node.dataset.id==="character:89")'), true, 'selected isolate stays in the first page')
  await click('定位人物')
  await pause(400)
  const pane = await run('(()=>{const r=document.querySelector(".author-atlas-canvas").getBoundingClientRect();return{x:Math.round(r.left+60),y:Math.round(r.top+70)}})()')
  win.webContents.sendInputEvent({ type: 'mouseDown', ...pane, button: 'left', clickCount: 1 })
  win.webContents.sendInputEvent({ type: 'mouseMove', x: pane.x + 55, y: pane.y + 30, movementX: 55, movementY: 30 })
  win.webContents.sendInputEvent({ type: 'mouseUp', x: pane.x + 55, y: pane.y + 30, button: 'left', clickCount: 1 })
  await pause(300)
  const before = await run('document.querySelector(".react-flow__viewport").getAttribute("style")')
  await click('人物')
  await wait('!!document.querySelector(".atlas-library")')
  await click('人物关系')
  await wait('document.querySelectorAll(".react-flow__node-character").length===80')
  await pause(350)
  assert.equal(await run('document.querySelector(".react-flow__viewport").getAttribute("style")'), before, 'pan and zoom survive leaving and returning to the graph')
  await run('window.showPerson("character:0")')
  await click('人物联系')
  await wait('document.querySelectorAll(".react-flow__node-character").length===7')
  for (const width of [900, 520]) {
    win.setContentSize(width, 1000); await pause(250)
    assert.equal(await run('document.documentElement.scrollWidth<=innerWidth'), true, width + 'px does not overflow horizontally')
    assert(await run('document.querySelector(".author-atlas-canvas").getBoundingClientRect().height>=440'), 'responsive graph retains usable canvas height')
    assert(await run('document.querySelector(".atlas-profile-panel").getBoundingClientRect().top>=document.querySelector(".relationship-graph-panel").getBoundingClientRect().bottom-1'), 'stacked inspector does not overlap the graph or relationship list')
    await click('适合画布'); await pause(200)
    await capture('relationships-focused-' + width + '.png')
  }
  assert.deepEqual(errors, [])
  fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify({ widths: [1440, 900, 520], characters: 90, relationships: 14, assertions: ['six-contact readable focus pages', 'all visible edge labels', 'always-open selected relationship list', 'isolated person beyond page 80', 'parent tab selection restoration', 'graph pan and zoom restoration', 'responsive no-horizontal-overflow', 'no renderer errors'] }, null, 2))
  win.destroy()
  console.log('[relationship-graph-ui] focus, labels, isolated selection, tab return, viewport persistence and 1440/900/520px layouts passed')
}
main().then(() => app.exit(0)).catch(error => { console.error(error); app.exit(1) })
