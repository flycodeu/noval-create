const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { app, BrowserWindow } = require('electron')
const { build } = require('esbuild')
const root = path.resolve(__dirname, '..')
const dir = fs.mkdtempSync(path.join(root, '.tmp-tests/author-redesign-ui-'))
app.setPath('userData', dir)
app.disableHardwareAcceleration()
app.commandLine.appendSwitch('force-device-scale-factor', '1')

async function main() {
  await app.whenReady()
  await build({ entryPoints: [path.join(__dirname, 'browser-fixtures/author-redesign.tsx')], outfile: path.join(dir, 'fixture.js'), bundle: true, alias: { '@': path.join(root, 'src') }, platform: 'browser' })
  fs.writeFileSync(path.join(dir, 'index.html'), '<meta charset="utf-8"><link rel="stylesheet" href="fixture.css"><div id="root"></div><script src="fixture.js"></script>')
  const win = new BrowserWindow({ show: false, width: 1280, height: 1000, useContentSize: true, webPreferences: { contextIsolation: false, nodeIntegration: false, backgroundThrottling: false } })
  const run = async code => { try { return await win.webContents.executeJavaScript(code) } catch (error) { console.error('Renderer code:', code); throw error } }
  const wait = async code => { for (let i = 0; i < 200; i++) { if (await run(`Boolean(${code})`)) return; await new Promise(resolve => setTimeout(resolve, 20)) } throw Error('Timeout: ' + code) }
  const click = text => run(`{const b=[...document.querySelectorAll('button')].find(b=>b.textContent.replace(/\\s/g,'')===${JSON.stringify(text.replace(/\s/g, ''))});if(!b)throw Error('Missing button');b.click()}`)
  const fill = (selector, value) => run(`{const el=document.querySelector(${JSON.stringify(selector)});const proto=el instanceof HTMLTextAreaElement?HTMLTextAreaElement.prototype:HTMLInputElement.prototype;Object.getOwnPropertyDescriptor(proto,'value').set.call(el,${JSON.stringify(value)});el.dispatchEvent(new Event('input',{bubbles:true}))}`)
  try {
    await win.loadFile(path.join(dir, 'index.html'))
    await wait('document.querySelector(".author-style-detail")?.textContent.includes("河边样稿")')
    for (const width of [1280, 720, 480]) {
      win.setContentSize(width + 1, 1000)
      await new Promise(resolve => setTimeout(resolve, 80))
      win.setContentSize(width, 1000)
      await new Promise(resolve => setTimeout(resolve, 150))
      assert(await run('document.documentElement.scrollWidth <= innerWidth + 1'), `no overflow at ${width}`)
      const png = await win.webContents.capturePage()
      fs.writeFileSync(path.join(dir, `style-${width}.png`), png.toPNG())
    }
    await click('新增样稿')
    await fill('textarea[aria-label="样稿正文"]', '雨从纸窗外落下。她把灯推近一点，听见井边有人叫自己的名字。')
    await wait('window.dirty===true')
    await click('河边样稿本作')
    await wait('document.querySelector(".author-style-detail")')
    await click('新增样稿')
    assert((await run('document.querySelector("textarea[aria-label=样稿正文]").value')).includes('雨从纸窗外'), 'switching samples retains input')
    await run('window.deferAnalyze=true')
    await click('分析并保存')
    await wait('window.resolveAnalyze')
    await click('分析并保存')
    assert.equal(await run('window.calls.filter(c=>c.toolId==="novelforge.style.analyze").length'), 1)
    assert(await run('document.querySelector("textarea[aria-label=样稿正文]").disabled'))
    await run('window.resolveAnalyze()')
    await wait('document.querySelector(".author-style-detail")?.textContent.includes("我的文风样稿")')
    await click('使用这份样稿')
    await wait('document.querySelector(".author-style-detail")?.textContent.includes("使用中")')
    await click('停用当前样稿')
    await wait('document.querySelector(".author-style-detail")?.textContent.includes("未使用")')
    await run('window.failGet=true')
    await click('外部样稿其他作品')
    await wait('document.body.textContent.includes("读取失败，请刷新样稿")')
    await run('window.failGet=false')
    await click('刷新样稿')
    await wait('document.querySelector(".author-style-detail")?.textContent.includes("外部样稿")')
    await click('复制到本作')
    await wait('document.querySelector(".author-style-detail")?.textContent.includes("外部样稿副本")')
    await fill('textarea[aria-label="试写场景梗概"]', '雨夜修灯')
    await click('同场景试写对照')
    await wait('document.querySelectorAll(".author-library-compare > div").length===2')
    await click('认可这份试写为样稿')
    await wait('document.querySelector(".author-style-detail")?.textContent.includes("试写样稿")')
    await run('window.paint("subplot")')
    await wait('document.body.textContent.includes("添加支线")')
    await click('添加支线')
    await fill('textarea[aria-label="支线 1 名称"]', '灯与去处')
    await wait('window.subplots[0]?.name==="灯与去处"')
    await click('移除支线 1')
    await wait('window.subplots.length===0')
    await run('window.paint("relation")')
    await wait('document.querySelector("input[aria-label=关系名称]")')
    await fill('input[aria-label="关系名称"]', '互相信任也会争执')
    await run('window.failSave=true')
    await click('保存')
    await wait('document.body.textContent.includes("版本冲突")')
    assert.equal(await run('document.querySelector("input[aria-label=关系名称]").value'), '互相信任也会争执')
    await run('window.failSave=false;window.deferSave=true')
    await click('保存')
    await wait('window.resolveSave')
    assert(await run('document.querySelector("input[aria-label=关系名称]").disabled'))
    await run('window.resolveSave()')
    await wait('window.saved===true && window.editorClosed===true')
    const payload = await run('window.applied.at(-1)')
    assert.equal(payload.expectedContextVersion, 9)
    assert.equal(payload.effectiveFromChapter, 3)
    assert.equal(payload.changes[0].status, 'planned')
    assert.equal(payload.changes[0].attributes.stateTiming, 'chapter_start')
    assert.equal(payload.changes[0].fromId, 'character:1')
    assert.equal(payload.changes[0].toId, 'character:2')
    assert(!('approval_source' in payload.changes[0].attributes))
    await run('window.paint("story")')
    await wait('document.querySelector(".story-direction")')
    for (const width of [1280, 480]) {
      win.setContentSize(width + 1, 1000)
      await new Promise(resolve => setTimeout(resolve, 80))
      win.setContentSize(width, 1000)
      await new Promise(resolve => setTimeout(resolve, 150))
      assert(await run('document.documentElement.scrollWidth <= innerWidth + 1'))
      fs.writeFileSync(path.join(dir, `story-${width}.png`), (await win.webContents.capturePage()).toPNG())
    }
    console.log('Author redesign UI passed; screenshots: ' + dir)
  } finally { win.destroy() }
}
main().then(() => app.exit(0)).catch(error => { console.error(error); app.exit(1) })
