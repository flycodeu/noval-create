const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { app, BrowserWindow } = require('electron')
const { build } = require('esbuild')
const root = path.resolve(__dirname, '..')
const dir = fs.mkdtempSync(path.join(root, '.tmp-tests/author-redesign-ui-'))
app.setPath('userData', dir)
app.disableHardwareAcceleration()
app.commandLine.appendSwitch('force-device-scale-factor', '1')

async function main() {
  await app.whenReady()
  await build({ entryPoints: [path.join(__dirname, 'browser-fixtures/author-redesign.tsx')], outfile: path.join(dir, 'fixture.js'), bundle: true, alias: { '@': path.join(root, 'src') }, platform: 'browser' })
  fs.writeFileSync(path.join(dir, 'index.html'), '<meta charset="utf-8"><link rel="stylesheet" href="fixture.css"><div id="root"></div><script src="fixture.js"></script>')
  const win = new BrowserWindow({ show: false, width: 1280, height: 1000, useContentSize: true, webPreferences: { contextIsolation: false, nodeIntegration: false, backgroundThrottling: false } })
  const run = async code => { try { return await win.webContents.executeJavaScript(code) } catch (error) { console.error('Renderer code:', code); throw error } }
  const wait = async code => { for (let i = 0; i < 200; i++) { if (await run(`Boolean(${code})`)) return; await new Promise(resolve => setTimeout(resolve, 20)) } throw Error('Timeout: ' + code) }
  const click = text => run(`{const b=[...document.querySelectorAll('button')].find(b=>b.textContent.replace(/\\s/g,'')===${JSON.stringify(text.replace(/\s/g, ''))});if(!b)throw Error('Missing button');b.click()}`)
  const fill = (selector, value) => run(`{const el=document.querySelector(${JSON.stringify(selector)});const proto=el instanceof HTMLTextAreaElement?HTMLTextAreaElement.prototype:HTMLInputElement.prototype;Object.getOwnPropertyDescriptor(proto,'value').set.call(el,${JSON.stringify(value)});el.dispatchEvent(new Event('input',{bubbles:true}))}`)
  try {
    await win.loadFile(path.join(dir, 'index.html'))
    await wait('document.querySelector(".author-style-detail")?.textContent.includes("河边样稿")')
    for (const width of [1280, 720, 480]) {
      win.setContentSize(width + 1, 1000)
      await new Promise(resolve => setTimeout(resolve, 80))
      win.setContentSize(width, 1000)
      await new Promise(resolve => setTimeout(resolve, 150))
      assert(await run('document.documentElement.scrollWidth <= innerWidth + 1'), `no overflow at ${width}`)
      const png = await win.webContents.capturePage()
      fs.writeFileSync(path.join(dir, `style-${width}.png`), png.toPNG())
    }
    await click('新增样稿')
    await fill('textarea[aria-label="样稿正文"]', '雨从纸窗外落下。她把灯推近一点，听见井边有人叫自己的名字。')
    await wait('window.dirty===true')
    await click('河边样稿本作')
    await wait('document.querySelector(".author-style-detail")')
    await click('新增样稿')
    assert((await run('document.querySelector("textarea[aria-label=样稿正文]").value')).includes('雨从纸窗外'), 'switching samples retains input')
    await run('window.deferAnalyze=true')
    await click('分析并保存')
    await wait('window.resolveAnalyze')
    await click('分析并保存')
    assert.equal(await run('window.calls.filter(c=>c.toolId==="novelforge.style.analyze").length'), 1)
    assert(await run('document.querySelector("textarea[aria-label=样稿正文]").disabled'))
    await run('window.resolveAnalyze()')
    await wait('document.querySelector(".author-style-detail")?.textContent.includes("我的文风样稿")')
    await click('使用这份样稿')
    await wait('document.querySelector(".author-style-detail")?.textContent.includes("使用中")')
    await click('停用当前样稿')
    await wait('document.querySelector(".author-style-detail")?.textContent.includes("未使用")')
    await run('window.failGet=true')
    await click('外部样稿其他作品')
    await wait('document.body.textContent.includes("读取失败，请刷新样稿")')
    await run('window.failGet=false')
    await click('刷新样稿')
    await wait('document.querySelector(".author-style-detail")?.textContent.includes("外部样稿")')
    await click('复制到本作')
    await wait('document.querySelector(".author-style-detail")?.textContent.includes("外部样稿副本")')
    await fill('textarea[aria-label="试写场景梗概"]', '雨夜修灯')
    await click('同场景试写对照')
    await wait('document.querySelectorAll(".author-library-compare > div").length===2')
    await click('认可这份试写为样稿')
    await wait('document.querySelector(".author-style-detail")?.textContent.includes("试写样稿")')
    await run('window.paint("graph")')
    await wait('document.querySelectorAll(".react-flow__node").length === 2')
    assert.deepEqual(await run('[...document.querySelectorAll(".react-flow__node")].map(node=>node.dataset.id).sort()'), ['character:1', 'character:2'], 'initial focus contains the anchor and its recorded contact')
    await wait('document.querySelectorAll(".react-flow__edge").length===1')
    assert((await run('document.querySelector(".relationship-readable-list").textContent')).includes('同行'), 'focused relationship remains readable')
    await click('全部人物 · 6')
    await wait('document.querySelectorAll(".react-flow__node").length === 6')
    await wait('document.querySelectorAll(".react-flow__edge").length===2')
    assert.equal(await run('document.querySelectorAll(".react-flow__edge").length'), 2, 'only the two recorded relationships are drawn')
    assert(!(await run('document.body.textContent')).includes('人物关系网络 ·'))
    win.setContentSize(1280, 1000)
    await new Promise(resolve => setTimeout(resolve, 250))
    const panelWidth = () => run('document.querySelector(".atlas-profile-panel").getBoundingClientRect().width')
    const beforeWidth = await panelWidth()
    await run('document.querySelector("[role=separator]").dispatchEvent(new KeyboardEvent("keydown",{key:"ArrowLeft",bubbles:true}))')
    await wait(`document.querySelector(".atlas-profile-panel").getBoundingClientRect().width > ${beforeWidth}`)
    assert(await panelWidth() > beforeWidth, 'keyboard expands the inspector')
    await run('document.querySelector("[role=separator]").dispatchEvent(new KeyboardEvent("keydown",{key:"Home",bubbles:true}))')
    await wait('Math.round(document.querySelector(".atlas-profile-panel").getBoundingClientRect().width)===260')
    assert.equal(Math.round(await panelWidth()), 260, 'minimum inspector width')
    const grip = await run('(()=>{const r=document.querySelector("[role=separator]").getBoundingClientRect();return{x:Math.round(r.x+r.width/2),y:Math.round(r.y+60)}})()')
    win.webContents.sendInputEvent({type:'mouseMove',...grip})
    win.webContents.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,...grip})
    win.webContents.sendInputEvent({type:'mouseMove',x:grip.x-90,y:grip.y})
    win.webContents.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,x:grip.x-90,y:grip.y})
    await new Promise(resolve => setTimeout(resolve, 100))
    assert(await panelWidth() >= 330, 'pointer dragging expands inspector')
    await run('[...document.querySelectorAll(".react-flow__node")].find(node => node.dataset.id === "character:3").click()')
    await wait('document.querySelector(".atlas-profile-panel h2").textContent==="渡船老板"')
    await click('人物联系')
    await wait('document.querySelectorAll(".react-flow__node").length===2')
    assert.deepEqual(await run('[...document.querySelectorAll(".react-flow__node")].map(node=>node.dataset.id).sort()'), ['character:3', 'character:4'], 'focus follows the selected person and only their recorded contact')
    await wait('document.querySelectorAll(".react-flow__edge").length===1')
    assert((await run('document.querySelector(".author-atlas-canvas").textContent')).includes('邻船货主'))
    assert(!(await run('document.querySelector(".author-atlas-canvas").textContent')).includes('林芷'))
    await run('document.querySelector(".relationship-readable-list button").click()')
    assert.equal(await run('window.clickedRelation'), 'r2', 'readable relationship opens the recorded relation')
    await click('全部人物 · 6')
    await wait('document.querySelectorAll(".react-flow__node").length===6')
    await wait('document.querySelectorAll(".react-flow__edge").length===2')
    for (const width of [1280, 720, 480]) {
      win.setContentSize(width + 1, 1000)
      await new Promise(resolve => setTimeout(resolve, 60))
      win.setContentSize(width, 1000)
      await new Promise(resolve => setTimeout(resolve, 200))
      assert(await run('document.documentElement.scrollWidth <= innerWidth + 1'), `graph overflow at ${width}`)
      fs.writeFileSync(path.join(dir, `graph-${width}.png`), (await win.webContents.capturePage()).toPNG())
    }
    win.setContentSize(1280, 1000)
    await run('window.paint("cast-edit")')
    await wait('document.querySelector("input[aria-label=人物作用]")')
    await run('[...document.querySelectorAll("details")].find(el=>el.textContent.includes("人物作用")).open=true')
    await run('document.querySelector("input[aria-label=人物作用]").closest(".ant-select-selector").dispatchEvent(new MouseEvent("mousedown",{bubbles:true}))')
    await wait('document.querySelectorAll(".ant-select-item-option-content").length>0')
    await run('[...document.querySelectorAll(".ant-select-item-option-content")].find(el=>el.textContent==="主角团").click()')
    await click('保存')
    await wait('window.castSaved===true')
    const castChange = await run('window.applied.at(-1)')
    assert.equal(castChange.expectedContextVersion, 9)
    assert.equal(castChange.changes[0].attributes.authorPlanning.castRole, 'companion')
    assert.equal(castChange.changes[0].attributes.authorPlanning.notes, '原有规划，不要覆盖')
    await run('window.paint("subplot")')
    await wait('document.body.textContent.includes("添加支线")')
    await click('添加支线')
    await fill('textarea[aria-label="支线 1 名称"]', '灯与去处')
    await wait('window.subplots[0]?.name==="灯与去处"')
    await click('移除支线 1')
    await wait('window.subplots.length===0')
    await run('window.paint("relation")')
    await wait('document.querySelector("input[aria-label=关系名称]")')
    await fill('input[aria-label="关系名称"]', '互相信任也会争执')
    await run('window.failSave=true')
    await click('保存')
    await wait('document.body.textContent.includes("版本冲突")')
    assert.equal(await run('document.querySelector("input[aria-label=关系名称]").value'), '互相信任也会争执')
    await run('window.failSave=false;window.deferSave=true')
    await click('保存')
    await wait('window.resolveSave')
    assert(await run('document.querySelector("input[aria-label=关系名称]").disabled'))
    await run('window.resolveSave()')
    await wait('window.saved===true && window.editorClosed===true')
    const payload = await run('window.applied.at(-1)')
    assert.equal(payload.expectedContextVersion, 9)
    assert.equal(payload.effectiveFromChapter, 3)
    assert.equal(payload.changes[0].status, 'planned')
    assert.equal(payload.changes[0].attributes.stateTiming, 'chapter_start')
    assert.equal(payload.changes[0].fromId, 'character:1')
    assert.equal(payload.changes[0].toId, 'character:2')
    assert(!('approval_source' in payload.changes[0].attributes))
    await run('window.paint("story")')
    await wait('document.querySelector(".story-direction")')
    for (const width of [1280, 480]) {
      win.setContentSize(width + 1, 1000)
      await new Promise(resolve => setTimeout(resolve, 80))
      win.setContentSize(width, 1000)
      await new Promise(resolve => setTimeout(resolve, 150))
      assert(await run('document.documentElement.scrollWidth <= innerWidth + 1'))
      fs.writeFileSync(path.join(dir, `story-${width}.png`), (await win.webContents.capturePage()).toPNG())
    }
    await run('window.paintReview()')
    await wait('document.querySelector(".chapter-review__header")')
    assert((await run('document.querySelector(".chapter-review__header").textContent')).includes('需要修订'))
    assert((await run('document.querySelector(".chapter-review__versions").textContent')).includes('审校正文 aaaaaaaa'))
    assert.equal(await run('document.querySelectorAll("section[aria-label=事实与边界] article").length'), 1)
    assert.equal(await run('document.querySelectorAll("section[aria-label=文风] article").length'), 1)
    await click('定位原文')
    assert(await run('window.located'))
    await run('window.reviewDirty=true;window.paintReview()')
    await wait('document.body.textContent.includes("草稿未保存")')
    assert(await run('[...document.querySelectorAll("button")].every(b=>b.disabled)'), 'old report actions cannot overwrite unsaved drafts')
    assert((await run('document.querySelector(".chapter-review__header").textContent')).includes('上次结论：需要修订'))
    await run('window.reviewDirty=false;window.reviewView.stale=true;window.reviewView.currentContentHash="b".repeat(64);window.reviewVersion="two";window.paintReview()')
    await wait('document.body.textContent.includes("当前保存 bbbbbbbb")')
    assert(await run('[...document.querySelectorAll("button")].every(b=>b.disabled)'))
    await run('window.reviewError=true;window.reviewVersion="error";window.paintReview()')
    await wait('document.body.textContent.includes("审校报告暂时不可用")')
    await run('window.reviewError=false;window.deferReview=true;window.reviewChapter=2;window.paintReview()')
    await wait('window.resolveReview && !document.body.textContent.includes("审校报告暂时不可用")')
    await run('window.resolveReview()')
    await wait('document.querySelector(".chapter-review__header")')
    for (const width of [1280, 480]) {
      win.setContentSize(width, 1000)
      await new Promise(resolve => setTimeout(resolve, 150))
      assert(await run('document.documentElement.scrollWidth <= innerWidth + 1'), `review panel overflow at ${width}`)
      fs.writeFileSync(path.join(dir, `review-${width}.png`), (await win.webContents.capturePage()).toPNG())
    }
    console.log('Author redesign UI passed; review versions, conclusion, grouping and stale/draft protection verified; screenshots: ' + dir)
  } finally { win.destroy() }
}
main().then(() => app.exit(0)).catch(error => { console.error(error); app.exit(1) })
