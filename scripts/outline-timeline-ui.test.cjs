const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {app,BrowserWindow}=require('electron'),{build}=require('esbuild');
const root=path.resolve(__dirname,'..'),tmp=path.join(root,'.tmp-tests');fs.mkdirSync(tmp,{recursive:true});
const dir=fs.mkdtempSync(path.join(tmp,'outline-timeline-ui-'));
app.setPath('userData',dir);app.disableHardwareAcceleration();
let win;const errors=[];
async function main(){
 await app.whenReady();
 await build({entryPoints:[path.join(__dirname,'browser-fixtures/outline-timeline.tsx')],outfile:path.join(dir,'fixture.js'),bundle:true,platform:'browser',alias:{'@':path.join(root,'src')}});
 fs.writeFileSync(path.join(dir,'index.html'),'<meta charset="utf-8"><link rel="stylesheet" href="fixture.css"><div id="root"></div><script src="fixture.js"></script>');
 win=new BrowserWindow({show:false,width:1280,height:900,webPreferences:{contextIsolation:false,nodeIntegration:false,backgroundThrottling:false}});
 win.webContents.on('console-message',(_,level,message)=>{if(level>=3&&!message.includes('Content-Security-Policy'))errors.push(message)});
 const run=code=>win.webContents.executeJavaScript(code);
 const wait=async code=>{for(let i=0;i<200;i++){if(await run(`Boolean(${code})`))return;await new Promise(r=>setTimeout(r,25))}throw Error('Timeout: '+code)};
 const count=(service,id)=>run(`window.calls.filter(c=>c.service===${JSON.stringify(service)}&&c.novelId===${id}).length`);
 await win.loadFile(path.join(dir,'index.html'));
 await wait('document.querySelectorAll(".story-outline-time-card").length===1');
 assert.equal(await count('atlas',1),1,'default decision and outline share one atlas read');
 assert.equal(await count('tree',1),1,'volume timeline reads the structure once');
 assert.equal(await count('chapters',1),0,'volume timeline does not load a second full chapter list');
 assert.equal(await count('novel',1),0,'volume timeline does not load unused novel details');
 await run('window.go("view=chapter")');
 await wait('document.querySelector(".story-timeline-event")?.textContent.includes("已经发生的事件")');
 assert.equal(await count('atlas',1),1,'switching to events reuses the same atlas');
 assert.equal(await count('chapters',1),1);assert.equal(await count('novel',1),1);
 await run('window.go("view=time")');
 await wait('document.querySelector("section[aria-label=故事时间事件]")');
 assert.equal(await count('atlas',1),1);assert.equal(await count('chapters',1),1);
 await run('window.go("view=volumes")');
 await wait('document.querySelectorAll(".story-outline-time-card").length===1');
 assert.equal(await count('atlas',1),1,'return to volumes still does not refetch atlas');
 await run('window.go("",2)');
 await wait('document.querySelector(".story-timeline-workspace")&&!document.querySelector(".author-loading")');
 assert.equal(await count('atlas',2),1);assert.equal(await count('tree',2),0,'books without volume outline records stay on the event timeline');
 assert.equal(await run('document.body.textContent.includes("第一卷·旧灯")'),false,'previous book outline is absent');
 await run('window.go("event=event%3Ascene",1)');
 await wait('document.querySelector(".story-timeline-detail h2")?.textContent==="已经发生的事件"');
 assert.equal(await count('atlas',1),2,'cross-book return reads current target atlas exactly once');
 assert.deepEqual(errors,[]);
 fs.writeFileSync(path.join(dir,'result.json'),JSON.stringify({ok:true,checks:['conditional default','explicit chapter/time views','event deep link','single shared atlas read','no unused full chapter list','cross-book scope'],calls:await run('window.calls'),errors},null,2));
 console.log('PASS outline/timeline default and shared-read UI; evidence '+dir);
}
main().then(()=>{win?.destroy();app.quit()}).catch(async error=>{console.error(error.stack);if(win){fs.writeFileSync(path.join(dir,'failure.png'),(await win.webContents.capturePage()).toPNG());win.destroy()}app.exit(1)});
