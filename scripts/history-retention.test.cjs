const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { app } = require('electron')
require('./isolate-test-session.cjs')(app)
const root = path.resolve(__dirname, '..')
const temp = path.join(root, '.tmp-tests')
fs.mkdirSync(temp, { recursive: true })
const profile = fs.mkdtempSync(path.join(temp, 'history-retention-'))
app.setPath('userData', profile)
process.env.NOVELFORGE_DISABLE_LEGACY_DB_COPY = '1'
require('./register-project-ts.cjs').registerProjectTsRuntime(root)

async function main() {
  await app.whenReady()
  const { initDb, getSqlite, closeDb } = require('../electron/database/db.ts')
  const service = require('../electron/services/history-retention.service.ts')
  const { logInfo } = require('../electron/utils/runtime-log.ts')
  initDb()
  try {
    const db = getSqlite()
    const novel = Number(db.prepare("INSERT INTO novels(title) VALUES ('清理隔离测试')").run().lastInsertRowid)
    const old = new Date(Date.now() - 45 * 86400000).toISOString()
    const recent = new Date(Date.now() - 2 * 86400000).toISOString()
    const add = (status = 'success', date = old, extra = {}) => {
      const id = Number(db.prepare('INSERT INTO tasks(novel_id,type,status,created_at,updated_at) VALUES(?,?,?,?,?)').run(novel, 'summary', status, date, date).lastInsertRowid)
      for (const [key, value] of Object.entries(extra)) db.prepare(`UPDATE tasks SET ${key} = ? WHERE id = ?`).run(value, id)
      return id
    }
    const removable = add()
    const recentId = add('failed', recent)
    const protectedIds = ['pending', 'running', 'paused', 'blocked', 'cancel_requested'].map(status => add(status))
    const activeParent = protectedIds[1]
    const child = add('success', old, { parent_task_id: activeParent })
    const upstream = add()
    db.prepare('UPDATE tasks SET upstream_task_id = ? WHERE id = ?').run(upstream, child)
    const draft = add('success', old, { progress_json: '{"draft":{"status":"pending"}}' })
    const planning = add('success', old, { type: 'planning_draft' })
    const provenance = add()
    db.prepare(`INSERT INTO artifacts(id,novel_id,kind,content_json,content_hash,context_version,producer_type,producer_id,producer_client,task_id)
      VALUES('kept-artifact',?,'review','{}','hash',1,'user','test','fixture',?)`).run(novel, provenance)
    const linked = add('success', old, { parent_task_id: provenance })
    const invalidDate = add('success', 'invalid date')
    const malformedProgress = add('success', old, { progress_json: '{legacy broken' })
    const updated = add('success', old, { updated_at: recent })
    const attempt = (id, status) => db.prepare(`INSERT INTO model_request_attempts(request_id,task_id,kind,provider,model_id,attempt_index,status,started_at)
      VALUES(?,?,'chat','fixture','test',1,?,?)`).run(`req-${id}`, id, status, old)
    attempt(removable, 'success')
    const started = add(); attempt(started, 'started')
    const reviewOrigin = add()
    db.prepare(`INSERT INTO revision_tasks(novel_id,title,origin_meta_json) VALUES(?,'保留审校来源',?)`).run(novel, JSON.stringify({ issueCategory: 'creative_review', runId: reviewOrigin }))
    assert.equal(service.getHistoryRetentionSettings().enabled, false)
    const settings = { enabled: false, keepDays: 30, cleanTasks: true, cleanLogs: true }
    assert.deepEqual(service.updateHistoryRetentionSettings(settings), settings)
    assert.throws(() => service.updateHistoryRetentionSettings({ ...settings, keepDays: 0 }))
    assert.throws(() => service.updateHistoryRetentionSettings({ ...settings, keepDays: 1.1 }))
    assert.throws(() => service.updateHistoryRetentionSettings({ ...settings, enabled: 'true' }))
    assert.throws(() => service.clearRetainedTaskHistory({ taskIds: [1, -1] }))
    const logs = path.join(profile, 'logs'); fs.mkdirSync(logs, { recursive: true })
    const oldLog = path.join(logs, 'main-runtime-2020-01-01.log')
    const unrelated = path.join(logs, 'author-notes.json')
    fs.writeFileSync(oldLog, 'old diagnostic log'); fs.utimesSync(oldLog, new Date(old), new Date(old))
    fs.writeFileSync(unrelated, 'never delete'); fs.utimesSync(unrelated, new Date(old), new Date(old))
    logInfo('fixture', 'current log survives')
    const before = db.prepare('SELECT count(*) AS n FROM tasks').get().n
    const preview = service.previewHistoryCleanup(settings)
    assert.equal(preview.taskCount, 1); assert.equal(preview.attemptCount, 1); assert.equal(preview.logCount, 1)
    assert.equal(db.prepare('SELECT count(*) AS n FROM tasks').get().n, before, 'preview is read-only')
    service.runDueHistoryCleanup()
    assert.equal(db.prepare('SELECT count(*) AS n FROM tasks').get().n, before, 'automatic cleanup is disabled by default')
    db.exec(`CREATE TRIGGER fail_cleanup BEFORE DELETE ON tasks WHEN OLD.id = ${removable} BEGIN SELECT RAISE(ABORT, 'forced cleanup failure'); END`)
    assert.throws(() => service.runHistoryCleanup(settings), /forced cleanup failure/)
    assert.equal(db.prepare('SELECT count(*) AS n FROM model_request_attempts WHERE task_id = ?').get(removable).n, 1, 'failed deletion retains calls')
    assert.equal(fs.existsSync(oldLog), true, 'task transaction failure does not delete logs')
    db.exec('DROP TRIGGER fail_cleanup')
    const result = service.runHistoryCleanup(settings)
    assert.deepEqual(result.deletedTaskIds, [removable]); assert.equal(result.deletedLogs, 1)
    assert.equal(db.prepare('SELECT count(*) AS n FROM model_request_attempts WHERE task_id = ?').get(removable).n, 0)
    for (const id of [recentId, ...protectedIds, child, upstream, draft, planning, provenance, linked, invalidDate, malformedProgress, updated, started, reviewOrigin]) {
      assert(db.prepare('SELECT id FROM tasks WHERE id = ?').get(id), 'protected row survives: ' + id)
    }
    assert.equal(fs.existsSync(oldLog), false); assert.equal(fs.existsSync(unrelated), true)
    assert(fs.readdirSync(logs).some(name => /^main-runtime-\d{4}-\d{2}-\d{2}\.log$/.test(name)))
    assert.equal(service.runHistoryCleanup(settings).deletedCount, 0, 'cleanup is idempotent')
    const manual = add('failed', recent)
    assert.deepEqual(service.clearRetainedTaskHistory({ taskIds: [manual] }).deletedTaskIds, [manual], 'explicit manual deletion can remove a recent unreferenced record')
    assert.equal(service.clearRetainedTaskHistory({ taskIds: [provenance] }).deletedCount, 0)
    const a = add(); const b = add('failed', old, { parent_task_id: a })
    assert.equal(service.clearRetainedTaskHistory({ taskIds: [a] }).deletedCount, 0, 'partial selection cannot orphan a child')
    assert.equal(service.clearRetainedTaskHistory({ taskIds: [a, b] }).deletedCount, 2, 'whole ended chain can be deleted')
    const auto = add()
    service.updateHistoryRetentionSettings({ ...settings, enabled: true })
    const originalNow = Date.now
    try {
      Date.now = () => originalNow() + 3_600_001
      service.runDueHistoryCleanup()
      assert.equal(db.prepare('SELECT id FROM tasks WHERE id = ?').get(auto), undefined, 'enabled hourly worker removes expired records')
    } finally { Date.now = originalNow }
    assert.deepEqual(db.pragma('foreign_key_check'), [])
    console.log('PASS history retention: validation, read-only preview, default-off scheduling, age/status/provenance/chain protection, transactional cascade, selective logs and manual deletion; isolated profile: ' + profile)
  } finally { closeDb() }
}
main().then(() => app.exit(0)).catch(error => { console.error(error); app.exit(1) })
