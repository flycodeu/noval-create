const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { app, BrowserWindow } = require('electron')
const { build } = require('esbuild')
const root = path.resolve(__dirname, '..')
fs.mkdirSync(path.join(root, '.tmp-tests'), { recursive: true })
const dir = fs.mkdtempSync(path.join(root, '.tmp-tests/novel-cover-ui-'))
app.setPath('userData', dir); app.disableHardwareAcceleration()
app.commandLine.appendSwitch('force-device-scale-factor', '1')
async function main() {
  await app.whenReady()
  await build({ entryPoints: [path.join(__dirname, 'browser-fixtures/novel-cover.tsx')], outfile: path.join(dir, 'fixture.js'), bundle: true, alias: { '@': path.join(root, 'src') }, platform: 'browser' })
  fs.writeFileSync(path.join(dir, 'index.html'), '<meta charset="utf-8"><link rel="stylesheet" href="fixture.css"><div id="root"></div><script src="fixture.js"></script>')
  const win = new BrowserWindow({ show: false, width: 1280, height: 1000, useContentSize: true, webPreferences: { contextIsolation: false, nodeIntegration: false, backgroundThrottling: false } })
  const run = async code => { try { return await win.webContents.executeJavaScript(code) } catch (error) { console.error('Renderer code:', code); throw error } }
  const wait = async code => { for (let i = 0; i < 250; i++) { if (await run(`Boolean(${code})`)) return; await new Promise(resolve => setTimeout(resolve, 20)) } throw Error('Timeout: ' + code) }
  const click = text => run(`{const el=[...document.querySelectorAll('button')].find(b=>b.textContent.replace(/\\s/g,'')===${JSON.stringify(text)}); if(!el)throw Error('Missing ${text}');el.click()}`)
  const fill = (selector, value) => run(`{const el=document.querySelector(${JSON.stringify(selector)});Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,${JSON.stringify(value)});el.dispatchEvent(new Event('input',{bubbles:true}))}`)
  const screenshots = async label => {
    for (const width of [1280, 720, 480]) {
      win.setContentSize(width + 1, 1000); await new Promise(resolve => setTimeout(resolve, 60))
      win.setContentSize(width, 1000); await new Promise(resolve => setTimeout(resolve, 450))
      await run('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))')
      assert(await run('document.documentElement.scrollWidth <= innerWidth + 1'), `${label}: no page overflow at ${width}`)
      assert(await run('[...document.querySelectorAll(".book-cover")].every(el => el.clientWidth > 60)'), 'cover remains visible')
      fs.writeFileSync(path.join(dir, `${label}-${width}.png`), (await win.webContents.capturePage()).toPNG())
    }
  }
  try {
    await win.loadFile(path.join(dir, 'index.html'))
    await wait('document.querySelectorAll(".novel-project-card").length===3')
    await screenshots('shelf')
    await run('window.paint("editor")')
    await wait('document.querySelector(".novel-cover-dialog")')
    await screenshots('cover-editor')
    // Upload a real PNG via the browser file input; accepting a preview must be explicit.
    await run(`{const input=document.querySelector('input[type=file]');const bytes=Uint8Array.from(atob(window.candidate.split(',')[1]),c=>c.charCodeAt(0));const transfer=new DataTransfer();transfer.items.add(new File([bytes],'cover.png',{type:'image/png'}));input.files=transfer.files;input.dispatchEvent(new Event('change',{bubbles:true}))}`)
    await wait('document.querySelector(".novel-cover-dialog__preview img")')
    assert.equal(await run('window.saved.length'), 0)
    await click('取消'); await wait('!document.querySelector(".novel-cover-dialog")')
    assert.equal(await run('window.saved.length'), 0, 'canceling imported preview leaves cover unchanged')
    await run('window.paint("shelf")'); await wait('document.querySelectorAll(".novel-project-card").length===3')
    await click('设置封面'); await wait('document.querySelector(".novel-cover-dialog")')
    // Select the configured image endpoint (text-only providers must not appear).
    await run('document.querySelector(".novel-cover-dialog .ant-select-selector").dispatchEvent(new MouseEvent("mousedown",{bubbles:true}))')
    await wait('document.querySelector(".ant-select-item-option")')
    assert(!(await run('document.querySelector(".ant-select-dropdown").textContent')).includes('Claude'))
    await run('document.querySelector(".ant-select-item-option").click()')
    await fill('input[aria-label="图片模型名"]', 'gpt-image-1')
    await run('window.deferGenerate=true')
    await click('生成封面'); await wait('window.resolveGenerate')
    assert(await run('[...document.querySelectorAll("button")].find(b=>b.textContent.includes("采用封面")).disabled'))
    await click('生成封面')
    assert.equal(await run('window.calls.length'), 1, 'double click cannot start duplicate paid requests')
    await run('window.resolveGenerate()')
    await wait('document.querySelector(".novel-cover-dialog__preview img")')
    assert.equal(await run('window.saved.length'), 0)
    await click('采用封面'); await wait('window.saved.length===1 && !document.querySelector(".novel-cover-dialog")')
    await wait('document.querySelector(".novel-project-card__cover img")')
    await run('window.paint("heading")'); await wait('document.querySelector(".novel-book-heading img")')
    assert.equal(await run('document.querySelector("textarea").value'), '这段草稿不会因更换封面丢失。')
    await screenshots('book-heading')
    await click('设置封面'); await wait('document.querySelector(".novel-cover-dialog")')
    await click('移除封面'); await run('window.failSave=true')
    await run('window.externalCoverChange()')
    await click('采用封面'); await wait('document.body.textContent.includes("封面已被其他操作修改")')
    assert.equal(await run('window.lastSaveInput.expectedCoverImage'), await run('window.candidate'), 'live prop updates cannot silently change the cover comparison baseline')
    assert(await run('Boolean(document.querySelector(".novel-cover-dialog"))'), 'conflicts retain preview')
    assert.equal(await run('window.saved.length'), 1)
    await run('window.failSave=false'); await click('采用封面'); await wait('window.saved.length===2')
    assert.equal(await run('window.saved[1].image'), null)
    console.log('Novel cover UI passed: upload/cancel, endpoint filtering, paid request deduplication, preview/adopt, shelf refresh, draft retention, CAS conflict and clear. Screenshots: ' + dir)
  } finally { win.destroy() }
}
main().then(() => app.exit(0)).catch(error => { console.error(error); app.exit(1) })
